ABSTRACT_TEXT = (
    "The exponential growth of digital communication platforms, social networking applications, and automated content "
    "generation pipelines has catalyzed an unprecedented crisis of digital misinformation, fabricated journalism, and "
    "coordinated deceptive narrative dissemination. Traditional approaches to veracity verification rely predominantly "
    "on human-driven investigative reporting and centralized fact-checking organizations (such as PolitiFact, FactCheck.org, "
    "and Snopes), which exhibit severe systemic bottlenecks regarding response latency, bandwidth limitations, and "
    "scalability constraints. In contraposition, modern deep neural network architectures—while achieving high empirical "
    "accuracy—introduce substantial computational overhead, multi-gigabyte memory footprints, and opaque 'black-box' "
    "decision manifolds that impede real-time deployment in high-throughput network environments. This project introduces a "
    "holistic, production-ready, high-performance machine learning system engineered specifically for real-time fake news "
    "identification and credibility scoring. The core mathematical engine leverages Term Frequency-Inverse Document Frequency "
    "(TF-IDF) feature vectorization coupled with a regularized online Passive-Aggressive Classifier (PAC). Unlike traditional "
    "batch-oriented classifiers, the Passive-Aggressive algorithm updates its decision hyperplanes incrementally in response "
    "to classification errors while maintaining strict margin-enforcing conservatism when predictions align with ground-truth "
    "labels, achieving an empirical test accuracy of 93.4% with sub-15ms inference latency. To overcome the interpretability "
    "limitations of linear classifiers, an automated heuristic sentiment analyzer runs concurrently, extracting typographic "
    "anomalies, all-caps emphasis ratios, punctuation spikes, and lexical triggers mapped against an extensive sensationalism "
    "lexicon. The inference pipeline is served via an asynchronous, non-blocking FastAPI backend equipped with cross-origin "
    "middleware, and integrated into a modern client-side single-page application built on React 18, Tailwind CSS, and Lucide "
    "icons styled under an immersive 'Antigravity' deep-space glassmorphism aesthetic. The resulting platform delivers instant "
    "credibility verdicts, calibrated probability margins, and granular linguistic risk breakdowns, establishing a viable "
    "framework for enterprise news verification, automated content moderation, and consumer digital literacy enablement."
)

